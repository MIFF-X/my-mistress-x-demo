export function getPlatformPlugins({ category, status, visibility } = {}) {
  return platformPluginRegistry.filter((plugin) => {
    if (category && plugin.category !== category) return false;
    if (status && plugin.status !== status) return false;
    if (visibility && !plugin.visibility.includes(visibility)) return false;
    return true;
  });
}

export function getPlatformPluginById(id) {
  return platformPluginRegistry.find((plugin) => plugin.id === id) || null;
}

export function getPlatformPluginProgressSummary() {
  const total = platformPluginRegistry.length;
  const average = Math.round(platformPluginRegistry.reduce((sum, plugin) => sum + plugin.progress, 0) / total);
  const byCategory = platformPluginRegistry.reduce((acc, plugin) => {
    acc[plugin.category] = acc[plugin.category] || { count: 0, progress: 0 };
    acc[plugin.category].count += 1;
    acc[plugin.category].progress += plugin.progress;
    return acc;
  }, {});

  Object.keys(byCategory).forEach((category) => {
    byCategory[category].averageProgress = Math.round(byCategory[category].progress / byCategory[category].count);
  });

  return { total, average, byCategory };
}
